/* ---------------------------------------------------------------------------
   brand/tokens.json, as data: the palette and the type from src/lib/palette.ts
   and nothing typed by hand. scripts/brand-export.mjs writes it;
   tests/unit/brand.test.ts compares the file on disk with this function, so
   the kit cannot drift from the app.
   --------------------------------------------------------------------------- */

import { GAUGE_FILLS, NIGHT_RIVER, PALETTE, PRINT_PAPER, STILLNESS, STILLNESS_INK, TYPE } from "../src/lib/palette.ts";

/** What each colour is for, in the words of DESIGNSYSTEM.md. */
const JOBS = {
  paper: "The ground of every page",
  paper2: "Tint ground for reference data (tables)",
  paper3: "Deeper tint, the masthead's fold",
  ink: "Type, the press's border, the horizon",
  ink2: "Secondary type",
  sindoor: "The one red. The press, the river's name, the sun, the seal, the bindu",
  marigold: "The one yellow. Where you pay or share, light on the water, the band's words",
  haldi: "Warm fills that are neither light nor money. Rare",
  teal: "The river. The waves, the gauge's deep end",
  maroon: "Festival days only, and the calendar-art ads",
  rule: "Hairlines in data tables only",
  wall: "The side walls of the press",
};

/** The CSS custom property each key is in globals.css. */
const CSS = { paper2: "--paper-2", paper3: "--paper-3", ink2: "--ink-2" };

export function brandTokens() {
  const colour = Object.fromEntries(
    Object.keys(PALETTE.day).map((k) => [
      k,
      { css: CSS[k] ?? `--${k}`, day: PALETTE.day[k], night: PALETTE.night[k], job: JOBS[k] },
    ]),
  );
  return {
    $comment: "Generated by `npm run brand` from src/lib/palette.ts. Edit palette.ts, never this file.",
    colour,
    onColour: {
      onMarigold: { hex: PALETTE.day.ink, job: "Type on marigold, day and night" },
      onSindoor: { hex: "#ffffff", job: "Type on sindoor, day and night" },
    },
    gauge: {
      bands: ["thin", "low", "usual", "full", "in spate"],
      widths: [1, 2, 4, 2, 1],
      day: [...GAUGE_FILLS.day],
      night: [...GAUGE_FILLS.night],
    },
    nightRiver: { ...NIGHT_RIVER },
    stillness: { ground: STILLNESS, ...STILLNESS_INK },
    printPaper: PRINT_PAPER,
    type: TYPE,
  };
}
